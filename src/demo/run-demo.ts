/**
 * End-to-end demo: "a current Berlin weather report, up to 1 USDC from approved providers".
 *
 *   npm run demo                 # auto-answers clarification and approvals
 *   npm run demo:interactive     # you answer the questions and approve on the "device"
 *   INTERPRETER=claude npm run demo   # use Claude for interpretation (needs Anthropic credentials)
 */
import { createInterface } from "node:readline/promises";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { startEnvironment, AGENT_2 } from "./environment.js";
import type { Decider } from "../grounding/approval.js";
import type { GroundRecord } from "../model.js";
import { fmt } from "../util/money.js";
import { postJson } from "../util/http.js";
import { AGENT_1 } from "./environment.js";

const interactive = process.argv.includes("--interactive");
const exportIdx = process.argv.indexOf("--export-examples");
const exportDir = exportIdx > 0 ? process.argv[exportIdx + 1] : undefined;
const rl = interactive ? createInterface({ input: process.stdin, output: process.stdout }) : undefined;
const h = (t: string) => console.log(`\n\x1b[1m━━ ${t}\x1b[0m`);
const say = (t: string) => console.log("  " + t);
function printEvaluations(evs: Array<{ acceptable: boolean; sellerName?: string; score: number; price?: string; currency?: string; reasons: string[] }>) {
  for (const ev of evs) {
    say(`${ev.acceptable ? "\x1b[32m✔" : "\x1b[31m✘"} ${ev.sellerName}\x1b[0m  score=${ev.score}  ${ev.price ? fmt(ev.price, ev.currency!) : ""}`);
    for (const reason of ev.reasons) say(`     ${reason}`);
  }
}
async function showBudget(gatewayUrl: string, mandateId: string) {
  const b = await (await fetch(`${gatewayUrl}/budget?mandate=${encodeURIComponent(mandateId)}`)).json() as any;
  say(`USDC mandate: ${fmt(b.settled, b.currency)} settled, ${fmt(b.available, b.currency)} available of ${fmt(b.limit, b.currency)}`);
}
/** Write the Pod's documents to disk with stable example IRIs (used for ontology/examples). */
async function exportExamples(env: Awaited<ReturnType<typeof startEnvironment>>, dir: string, txDocs: string[]) {
  const docs = [env.layout.profile, env.layout.wallet, ...txDocs];
  for (const c of [env.layout.commonGround, env.layout.preferences, env.layout.mandates]) docs.push(...(await env.pod.list(c)));
  const rename: Array<[string, string]> = [
    [env.podRoot, "https://alice.example/"],
    [env.sellers.spree.url, "https://spree-weather.example"], [env.sellers.havel.url, "https://havel-data.example"], [env.sellers.shady.url, "https://shady-forecasts.example"],
    [env.signer.url, "https://signer.alice.example"],
  ];
  mkdirSync(dir, { recursive: true });
  for (const d of docs) {
    let text = (await env.pod.get(d))!.text;
    for (const [from, to] of rename) text = text.replaceAll(from, to);
    const name = d.includes("/transactions/") ? (d.endsWith("-ledger.ttl") ? "transaction-ledger.ttl" : "transaction.ttl")
      : d.slice(env.podRoot.length).replace(/^commerce\//, "").replace(/\//g, "_");
    writeFileSync(join(dir, name.endsWith(".ttl") ? name : name + ".ttl"), `# Generated by \`npm run demo -- --export-examples ${dir}\` (real output, IRIs renamed)\n` + text);
  }
  say(`Exported ${docs.length} Pod documents to ${dir}`);
}

/** What a compromised agent might try: rewrite every decimal limit in the mandate to 100. */
const raiseLimits = (ttl: string) => ttl.replace(/odrl:rightOperand (?:"\d+(?:\.\d+)?"\^\^xsd:decimal|\d+\.\d+)/g, 'odrl:rightOperand "100.00"^^xsd:decimal');
const agentLog = (who: string) => (l: string) => console.log(`  \x1b[2m[${who}] ${l}\x1b[0m`);

const decider: Decider = async (summary) => {
  console.log("\n  \x1b[33m┌─ approval device ─────────────────────────────\x1b[0m");
  for (const line of summary.split("\n")) console.log("  \x1b[33m│\x1b[0m " + line);
  if (!rl) { console.log("  \x1b[33m└─ (auto-approved)\x1b[0m"); return true; }
  const a = await rl.question("  \x1b[33m└─ approve? [y/N] \x1b[0m");
  return /^y/i.test(a.trim());
};

async function main() {
  h("Starting Solid server, simulated payment rails, sellers, signer and gateway");
  const env = await startEnvironment({ decider });
  say(`Buyer Pod:   ${env.podRoot}`);
  say(`Sellers:     Spree Weather (approved), Havel Data (approved), Shady Forecasts (NOT approved)`);
  say(`Wallet:      x402 payer ${env.signer.evmAddress} with ${fmt(env.rails.facilitator.chain.balanceOf(env.signer.evmAddress), "USDC")} (simulated)`);
  const approved = env.registry.list().map((s) => s.webId);

  try {
    // ---------------------------------------------------------------- session 1
    h("Session 1: understanding the request");
    const text = "Get me a current Berlin weather report. I prefer providers that include an hourly forecast. You may spend up to 1 USDC from approved providers.";
    say(`User: "${text}"`);
    const a1 = env.assistant(undefined, { log: agentLog("assistant-1") });
    const { ctx, result } = await a1.understand(text, approved);
    for (const n of result.notes) say("note: " + n);

    const proposals: GroundRecord[] = [...result.proposals];
    for (const q of result.questions) {
      h(`Clarification: "${q.term}"`);
      say(q.prompt);
      q.options.forEach((o, i) => say(`  ${i + 1}) ${o.label}`));
      let choice = 1;
      if (rl) choice = Math.max(0, Math.min(q.options.length - 1, Number(await rl.question("  choose: ")) - 1 || 0));
      else say(`  → user picks 2) ${q.options[1].label}`);
      proposals.push(...a1.answer(q, choice, ctx));
    }

    h("Confirming common ground and spending authority (separately)");
    const { confirmed, rejected } = await a1.confirm(proposals, env.device);
    say(`${confirmed.length} record(s) written to the Pod, ${rejected.length} rejected`);
    const mandate = confirmed.find((r) => r.kind === "mandate");
    if (!mandate) { say("No spending mandate was approved; stopping."); return; }

    h("Session 1: purchase");
    const r1 = await a1.purchase({ text, category: result.intention!.category, subject: result.intention!.subject, mandateId: mandate.id });
    printEvaluations(r1.evaluations);
    say(`Result: \x1b[1m${r1.status}\x1b[0m  ${r1.scheme ?? ""} ${r1.amount ? fmt(r1.amount, r1.currency!) : ""}`);
    if (r1.content) say(`Report: ${JSON.stringify(r1.content)}`);
    for (const c of r1.delivery?.checks ?? []) say(`  ${c}`);
    say(`Evidence in Pod: ${r1.evidence}`);
    await showBudget(env.gateway.url, mandate.id);
    if (exportDir) await exportExamples(env, exportDir, [r1.evidence!, r1.evidence!.replace(/\.ttl$/, "-ledger.ttl")]);

    // ---------------------------------------------------------------- session 2
    h("Session 2: fresh assistant instance, no memory except the Pod");
    const a2text = "Get me a current Berlin weather report.";
    say(`User: "${a2text}"`);
    const fresh = env.assistant(undefined, { log: agentLog("assistant-1, new session") });
    const u2 = await fresh.understand(a2text, approved);
    say(`Clarification questions: ${u2.result.questions.length}. The agreed meaning of "current" is read from the Pod.`);
    say(`Reused: ${u2.result.reused.map((r) => (r.kind === "meaning" ? `meaning "${r.term}"` : r.kind)).join(", ")}`);
    const r2 = await fresh.purchase({ text: a2text, category: "WeatherReport", subject: "Berlin", mandateId: mandate.id });
    say(`Result: \x1b[1m${r2.status}\x1b[0m`);

    h("A second, different agent reads the same common ground");
    const other = env.assistant(AGENT_2, { log: agentLog("assistant-2") });
    const r2b = await other.purchase({ text: a2text, category: "WeatherReport", subject: "Berlin", mandateId: mandate.id });
    say(`Result: \x1b[1m${r2b.status}\x1b[0m ${r2b.code ?? ""}`);
    say("Preferences carry over; spending authority does not (assistant-2 is not an assignee of the mandate).");

    // ---------------------------------------------------------------- guardrails
    h("Guardrail: someone edits the mandate in the Pod to raise the limit to 100 USDC");
    const doc = mandate.id.split("#")[0];
    const orig = (await env.pod.get(doc))!.text;
    await env.pod.putTurtle(doc, raiseLimits(orig));
    const r3 = await a1.purchase({ text, category: "WeatherReport", subject: "Berlin", mandateId: mandate.id });
    say(`Assistant: \x1b[1m${r3.status}\x1b[0m ${r3.code}: ${r3.reason}`);
    const offer = env.sellers.spree.currentOffer();
    const direct = await postJson(`${env.gateway.url}/authorize`, { transactionId: "tx-bypass", agentId: AGENT_1, mandateId: mandate.id, offer, option: { scheme: "x402", amount: offer.payload.prices[0].amount, currency: "USDC", payTo: offer.payload.prices[0].payTo, resource: offer.payload.resource, challenge: {} } });
    say(`Gateway, called directly by a compromised agent: ${direct.status} ${direct.body.code}: ${direct.body.reason}`);
    await env.pod.putTurtle(doc, orig);

    h("Guardrail: the seller raises its price between evaluation and payment");
    const r4 = await a1.purchase({ text, category: "WeatherReport", subject: "Berlin", mandateId: mandate.id, hooks: { afterEvaluation: async () => env.sellers.spree.setPrice({ x402: "0.03" }) } });
    for (const n of r4.notes) say("note: " + n);
    say(`Result: \x1b[1m${r4.status}\x1b[0m, paid ${r4.amount ? fmt(r4.amount, r4.currency!) : "-"} against offer v${r4.selected?.version}`);

    // ---------------------------------------------------------------- other 402 protocols
    h("Same HTTP 402 endpoint, other payment protocols");
    for (const [label, sentence] of [
      ["L402-style (Lightning-like invoice + macaroon)", "You may spend up to 100 sats on weather reports from approved providers."],
      ["card / PSP payment intent", "You may spend up to 1 EUR on weather reports from approved providers."],
    ] as const) {
      say(`\x1b[1m${label}\x1b[0m: "${sentence}"`);
      const u = await a1.understand(sentence, approved);
      const { confirmed: c } = await a1.confirm(u.result.proposals, env.device);
      const m = c.find((r) => r.kind === "mandate")!;
      const r = await a1.purchase({ text: a2text, category: "WeatherReport", subject: "Berlin", mandateId: m.id });
      say(`  → ${r.status} via ${r.scheme}, ${r.amount ? fmt(r.amount, r.currency!) : "-"}`);
    }

    h("Final state");
    await showBudget(env.gateway.url, mandate.id);
    say(`Spree Weather received: ${fmt(env.rails.facilitator.chain.balanceOf(env.sellers.spree.payTo), "USDC")} (x402), ${env.rails.lightning.balances.get(env.sellers.spree.lightningPayee) ?? 0} sats (L402), ${fmt(String(env.rails.psp.merchantBalances.get(env.sellers.spree.merchantId) ?? 0), "EUR")} (card)`);
    say(`Pod records under ${env.layout.commerce}:`);
    for (const c of [env.layout.commonGround, env.layout.preferences, env.layout.mandates, env.layout.transactions]) {
      const items = await env.pod.list(c);
      say(`  ${c.slice(env.layout.commerce.length)}  ${items.length} document(s)`);
    }
    if (interactive) await rl!.question("\n  Press Enter to stop the servers (the Pod is in memory and will be discarded) ");
  } finally {
    rl?.close();
    await env.close();
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
